// Syntax follows dsh-oks draft/dom.ts and draft/typed-syntax.ts.
const PREC = {lambda: -1, coalesce: 1, or: 2, and: 3, equality: 4, comparison: 5, additive: 6, multiplicative: 7, unary: 8, access: 9};
const commaSep = rule => optional(seq(rule, repeat(seq(',', rule)), optional(',')));
module.exports = grammar({
  name: 'dari',
  extras: $ => [/\s/, $.comment],
  word: $ => $.identifier,
  conflicts: $ => [[$._expression, $.parameters]],
  rules: {
    source_file: $ => repeat($._declaration),
    _declaration: $ => choice($.data_declaration, $.figure_declaration, $.report_declaration, $.answer_declaration),
    data_declaration: $ => seq('data', field('name', $.identifier), ':=', field('value', $._expression), ';'),
    figure_declaration: $ => seq('figure', field('name', $.identifier), ':=', field('value', $.node), ';'),
    report_declaration: $ => seq('report', field('name', $.identifier), ':=', field('value', $.node), ';'),
    answer_declaration: $ => seq('answer', ':=', field('value', $.node), ';'),
    node: $ => seq(field('tag', $.tag_name), optional($.attributes), optional($.children)),
    tag_name: _ => /[A-Za-z_$][A-Za-z0-9_$:-]*/,
    attributes: $ => seq('(', commaSep($.attribute), ')'),
    attribute: $ => seq(field('name', $.tag_name), '=', field('value', $._expression)),
    children: $ => seq('[', commaSep(choice($.string, $.node)), ']'),
    _expression: $ => choice($.identifier, $.number, $.string, $.boolean, $.null, $.array, $.object,
      $.parenthesized_expression, $.lambda_expression, $.call_expression, $.member_expression,
      $.subscript_expression, $.unary_expression, $.binary_expression),
    identifier: _ => /[A-Za-z_$][A-Za-z0-9_$]*/,
    number: _ => /(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?/,
    string: $ => seq('"', repeat(choice($.string_content, $.escape_sequence)), '"'),
    string_content: _ => token.immediate(prec(1, /[^"\\\x00-\x1f]+/)),
    escape_sequence: _ => token.immediate(prec(1, /\\(?:["\\/bfnrt]|u[0-9a-fA-F]{4})/)),
    boolean: _ => choice('true', 'false'),
    null: _ => 'null',
    array: $ => seq('[', commaSep($._expression), ']'),
    object: $ => seq('{', commaSep(choice($.pair, $.shorthand_property)), '}'),
    pair: $ => seq(field('key', choice($.identifier, $.string)), ':', field('value', $._expression)),
    shorthand_property: $ => choice($.identifier, $.string),
    parenthesized_expression: $ => seq('(', $._expression, ')'),
    lambda_expression: $ => prec.right(PREC.lambda, seq(
      field('parameters', choice($.identifier, $.parameters)), '=>', field('body', $._expression))),
    parameters: $ => seq('(', optional(seq($.identifier, repeat(seq(',', $.identifier)))), ')'),
    call_expression: $ => prec(PREC.access, seq(field('function', $.identifier), field('arguments', $.arguments))),
    arguments: $ => seq('(', commaSep($._expression), ')'),
    member_expression: $ => prec.left(PREC.access, seq(field('object', $._expression),
      field('operator', choice('.', '?.')), field('property', $.identifier))),
    subscript_expression: $ => prec.left(PREC.access, seq(field('object', $._expression), '[',
      field('index', choice($.string, $.number)), ']')),
    unary_expression: $ => prec(PREC.unary, seq(field('operator', choice('!', '-')), field('argument', $._expression))),
    binary_expression: $ => choice(...[
      [PREC.coalesce, '??'], [PREC.or, '||'], [PREC.and, '&&'],
      [PREC.equality, '=='], [PREC.equality, '!='],
      ...['<', '>', '<=', '>='].map(op => [PREC.comparison, op]),
      ...['+', '-'].map(op => [PREC.additive, op]),
      ...['*', '/', '%'].map(op => [PREC.multiplicative, op]),
    ].map(([level, op]) => prec.left(level, seq(field('left', $._expression), field('operator', op), field('right', $._expression))))),
    comment: _ => token(choice(seq('//', /[^\r\n]*/), seq('/*', /[^*]*\*+([^/*][^*]*\*+)*/, '/'))),
  },
});
