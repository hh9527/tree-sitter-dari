// The declarative language in lab-ontology/dari/src/syntax.ts is authoritative.
const PREC={pipe:0,or:1,and:2,equality:3,comparison:4,additive:5,multiplicative:6,unary:7,access:8};
const commaSep=r=>optional(seq(r,repeat(seq(',',r)),optional(',')));
module.exports=grammar({
 name:'dari',extras:$=>[/\s/,$.comment],word:$=>$.identifier,
 rules:{
  source_file:$=>repeat($._declaration),
  _declaration:$=>choice($.type_declaration,$.data_declaration,$.report_declaration,$.answer_declaration),
  type_declaration:$=>seq('type',field('name',$.identifier),'=',field('value',$._type),';'),
  data_declaration:$=>seq('data',field('name',$.identifier),optional(seq(':',field('type',$._type))),'=',field('value',$._expression),';'),
  report_declaration:$=>seq('report',field('name',$.identifier),'=',field('value',$.tree_expression),';'),
  answer_declaration:$=>seq('answer',field('value',$.tree_expression),';'),
  _type:$=>choice($.type_identifier,$.constructed_type,$.schema_type,$.intersection_type),
  type_identifier:$=>choice($.identifier,$.scoped_identifier),
  constructed_type:$=>seq(field('constructor',$.type_identifier),'(',field('inner',$._type),')'),
  schema_type:$=>seq('Schema','(','{',commaSep($.schema_field),'}',')'),
  schema_field:$=>seq(field('name',choice($.identifier,$.string)),':',field('type',$._type)),
  intersection_type:$=>prec.left(seq(field('left',$._type),'&',field('right',$._type))),
  _expression:$=>choice($.identifier,$.scoped_identifier,$.number,$.string,$.boolean,$.null,$.array,$.object,$.parenthesized_expression,$.call_expression,$.member_expression,$.subscript_expression,$.unary_expression,$.binary_expression,$.query_expression,$.context_expression,$.projection_expression,$.do_expression,$.tree_expression,$.postfix_binding,$.unwrap_or_expression,$.postfix_unwrap_or),
  identifier:_=>/[A-Za-z_][A-Za-z_0-9]*/,
  scoped_identifier:$=>seq($.identifier,repeat1(seq('::',$.identifier))),
  number:_=>/\d+(?:\.\d+)?/,
  string:$=>seq('"',repeat(choice($.string_content,$.escape_sequence)),'"'),
  string_content:_=>token.immediate(prec(1,/[^"\\\x00-\x1f]+/)),
  escape_sequence:_=>token.immediate(prec(1,/\\(?:["\\/bfnrt]|u[0-9a-fA-F]{4})/)),
  boolean:_=>choice('True','False'),null:_=>'None',
  array:$=>seq('[',commaSep($._expression),']'),
  object:$=>seq('{',commaSep(choice($.pair,$.shorthand_property)),'}'),
  pair:$=>seq(field('key',choice($.identifier,$.string)),':',field('value',$._expression)),
  shorthand_property:$=>choice($.identifier,$.string),
  parenthesized_expression:$=>seq('(',$._expression,')'),
  call_expression:$=>prec(PREC.access,seq(field('function',choice($.identifier,$.scoped_identifier,alias('project',$.identifier))),field('arguments',$.arguments))),
  arguments:$=>seq('(',commaSep($._expression),')'),
  member_expression:$=>prec.left(PREC.access,seq(field('object',$._expression),'.',field('property',$.identifier))),
  subscript_expression:$=>prec.left(PREC.access,seq(field('object',$._expression),'[',field('index',$.number),']')),
  postfix_binding:$=>prec.left(PREC.access,seq(field('value',$._expression),'.','as','!','(',field('name',$.identifier),')')),
  unwrap_or_expression:$=>seq('unwrap_or','!',$.arguments),
  postfix_unwrap_or:$=>prec.left(PREC.access,seq(field('value',$._expression),'.','unwrap_or','!',$.arguments)),
  unary_expression:$=>prec(PREC.unary,seq('-',field('argument',$._expression))),
  binary_expression:$=>choice(...[[PREC.or,'||'],[PREC.and,'&&'],[PREC.equality,'=='],[PREC.equality,'!='],...['<','>','<=','>='].map(o=>[PREC.comparison,o]),...['+','-'].map(o=>[PREC.additive,o]),...['*','/','%'].map(o=>[PREC.multiplicative,o])].map(([level,op])=>prec.left(level,seq(field('left',$._expression),field('operator',op),field('right',$._expression))))),
  query_expression:$=>seq(field('macro',choice('query','query_remote')),'!','{',repeat($.let_declaration),field('result',$._plan_expression),optional(';'),'}'),
  _plan_expression:$=>choice($._expression,$.pipeline_expression),
  pipeline_expression:$=>prec.left(PREC.pipe,seq(field('input',$._expression),repeat1(seq('|>',field('operation',$._expression))))),
  let_declaration:$=>seq('let',field('name',$.identifier),'=',field('value',$._plan_expression),';'),
  do_expression:$=>seq('do','{',repeat($.let_declaration),field('result',$._expression),optional(';'),'}'),
  context_expression:$=>seq('context','!',$.object),
  projection_expression:$=>prec.right(seq('$',repeat1(seq('.',field('field',$.identifier),optional('?'))))),
  tree_expression:$=>seq('tree','!','{',field('root',$.node),'}'),
  node:$=>seq(field('tag',$.tag_name),optional($.attributes),optional($.children)),
  tag_name:$=>$.identifier,
  attributes:$=>seq('(',commaSep($.attribute),')'),
  attribute:$=>seq(field('name',$.identifier),'=',field('value',$._expression)),
  children:$=>seq('[',commaSep(choice($.string,$.node,$.if_node)),']'),
  if_node:$=>prec.right(seq('if',choice(seq('let','Some','(',field('binding',$.identifier),')','=',field('value',$._expression)),field('condition',$._expression)),field('consequence',$.children),seq('else',field('alternative',$.children)))),
  comment:_=>token(seq('#',/[^\r\n]*/)),
 }
});